// Builds everything that is generated:
//   src/generated/chart-view.ts   the MCP App widget as one self-contained HTML string
//   public/canvas.html + .js      the canvas page
//   api/mcp.js, api/canvas.js     the serverless functions, bundled (Vercel serves api/*)
// Run by `npm run build`, and automatically before `dev` and `test`.
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...a) => join(root, ...a);
const only = process.argv[2]; // "view" builds just the browser parts (fast, used by tests)

await Promise.all(['src/generated', 'public', 'api'].map((d) => mkdir(p(d), { recursive: true })));

// The shared stylesheet lives in render.ts; pull it out by bundling and evaluating that one export.
const cssBundle = await build({
  entryPoints: [p('src/view/render.ts')], bundle: true, write: false, format: 'esm', platform: 'node', logLevel: 'silent',
});
const css = (await import(`data:text/javascript;base64,${Buffer.from(cssBundle.outputFiles[0].text).toString('base64')}`)).CHART_CSS;

const browser = { bundle: true, minify: true, format: 'iife', platform: 'browser', target: 'es2022', write: false, logLevel: 'warning' };
const [widget, canvas] = await Promise.all([
  build({ ...browser, entryPoints: [p('src/view/chart-view.ts')] }),
  build({ ...browser, entryPoints: [p('src/view/canvas.ts')] }),
]);

// A </script> inside the bundle would end the inline script early.
const inline = (js) => js.replace(/<\/script/gi, '<\\/script');
const widgetHtml = (await readFile(p('src/view/chart.html'), 'utf8'))
  .replace('/*CSS*/', () => css)
  .replace('/*SCRIPT*/', () => inline(widget.outputFiles[0].text));
await writeFile(p('src/generated/chart-view.ts'), `// Generated by scripts/build.mjs. Do not edit.\nexport const CHART_VIEW_HTML = ${JSON.stringify(widgetHtml)};\n`);

await writeFile(p('public/canvas.js'), canvas.outputFiles[0].text);
await writeFile(p('public/canvas.html'), (await readFile(p('src/view/canvas.html'), 'utf8')).replace('/*CSS*/', () => css));

if (only !== 'view') {
  const fn = { bundle: true, format: 'esm', platform: 'node', target: 'node20', minify: false, logLevel: 'warning',
    banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" } };
  await Promise.all([
    build({ ...fn, entryPoints: [p('src/entries/mcp.ts')], outfile: p('api/mcp.js') }),
    build({ ...fn, entryPoints: [p('src/entries/canvas.ts')], outfile: p('api/canvas.js') }),
  ]);
}
console.log(`built (${Math.round(widgetHtml.length / 1024)} KB widget)`);
